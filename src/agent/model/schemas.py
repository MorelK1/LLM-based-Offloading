"""Domain schemas shared across the pipeline."""

from typing import Literal

from pydantic import BaseModel, Field


class Node(BaseModel):
    node_id: str
    node_name: str
    tier: Literal["iot", "edge", "fog", "cloud"]
    node_type: str
    cpu_cores: int
    ram_gb: int
    storage_gb: int
    mips: float | None = None


class Link(BaseModel):
    link_id: str
    source_node: str
    target_node: str
    link_type: str
    bandwidth_mbps: int
    # Pure signal-propagation delay (prop_uv), independent of data volume --
    # distinct from transmission delay (output_size/bandwidth), which is
    # computed per-service, not stored on the link. See
    # utils/pipeline.py:shortest_path_delays_ms.
    propagation_delay_ms: float
    packet_loss_rate: float
    reliability: float


class Service(BaseModel):
    service_id: str
    name: str
    description: str
    current_node: str
    requirements: dict[str, float] | None = None
    # Both solvers treat this service's node as immovable: it must stay on
    # current_node in every candidate/solution, never counted as "moved".
    # See utils/csp_solver.py:solve_placement and
    # utils/csp_constraints_cp_sat.py:add_fixed_placement_constraints_cp_sat.
    fixed_placement: bool = False
    wcet_ms: float | None = None
    workload_mi: float | None = None
    # Data volume this service emits per invocation, in megabits (Mb) -- the
    # same unit family as Link.bandwidth_mbps. See
    # utils/pipeline.py:shortest_path_delays_ms for how this becomes a
    # transmission delay.
    output_size: float | None = None


class Flow(BaseModel):
    """A directed, ordered chain of services forming one logical dataflow
    through the application (e.g. capture -> detection -> alert). Several
    flows may share services at their endpoints without that being a "merge"
    at the flow level -- each flow is independently a simple path, so there
    is never more than one predecessor/successor *within* a given flow.
    Latency (cumulative_flow_latency_ms) is always computed by walking path,
    never stored -- see utils/pipeline.py.
    """

    flow_id: str
    name: str
    description: str
    path: list[str]  # service_ids, in order, root -> terminal
    requirements: dict[str, float] | None = None


class Application(BaseModel):
    application_id: str
    name: str
    flows: list[Flow]


# Discrete set of KPIs / units the LLM may choose from, so it can't hallucinate
# free-form values. Extend these lists deliberately if a new KPI or unit is
# needed.
KpiType = Literal["cpu", "ram", "latency"]
# Every unit the extraction LLM is allowed to emit, across all three KPI
# types -- the model is expected to pick whichever one matches the intent's
# OWN phrasing (e.g. "500 millicores" -> unit="millicore"), never to convert
# units itself. utils/pipeline.py:to_native_unit() does the actual
# validation + conversion to each KPI's canonical unit (vCPU / GB / ms)
# immediately after extraction, before any downstream node sees the
# requirement -- see intent_grounding_node.
Unit = Literal[
    # cpu -> vCPU
    "vCPU", "CPU", "core", "cores", "millicore", "mCPU", "m",
    # ram -> GB (decimal: KB/MB/GB/TB; binary: KiB/MiB/GiB/TiB)
    "KB", "MB", "GB", "TB", "KiB", "MiB", "GiB", "TiB",
    # latency -> ms
    "µs", "us", "ms", "s", "seconds",
]
TargetType = Literal["service", "flow"]


class ExtractedRequirement(BaseModel):
    """Requirement fields the LLM is asked to fill via structured output.

    requirement_id is intentionally excluded: it must be assigned
    deterministically by code (incremented as requirements come in), not
    generated by the model.
    """

    kpi_type: KpiType = Field(description="KPI targeted by the requirement")
    comparator: Literal["gte", "lte", "eq"] = Field(description="Comparison operator applied to target_value")
    target_value: float = Field(description="Numeric threshold for the KPI")
    unit: Unit = Field(description="Unit of target_value")
    target_type: TargetType = Field(description="Whether the requirement targets a single service or a flow")
    target_id: str = Field(description="service_id (if target_type=service) or flow_id (if target_type=flow)")
    source_span: str = Field(description="Exact excerpt from the source text expressing this requirement")


class ExtractedRequirementList(BaseModel):
    """Wrapper schema used to request a list of requirements via structured output."""

    requirements: list[ExtractedRequirement]


class Requirement(ExtractedRequirement):
    """Structured requirement extracted from a natural-language intent, with a
    deterministic requirement_id assigned by code."""

    requirement_id: str = Field(description="Unique identifier, e.g. 'req-001'")


class NecessityCheckResult(BaseModel):
    status: Literal["reconfiguration_required", "reconfiguration_not_required"]
    # Human-readable (ok=False) reasons from capacity_satisfied/latency_satisfied
    # -- which node/flow failed and why, not which requirement_id "caused" it:
    # a violation can come from several active requirements combined (e.g. two
    # co-located services each getting a new cpu floor that together overflow
    # their shared node), so attributing it to a single requirement would be
    # arbitrary. See necessity_checker.py.
    violated_constraints: list[str]
    current_placement: dict[str, str] | None = None


class DecisionResult(BaseModel):
    # FEASIBLE: a valid placement was found (decision may still be empty if
    # the search converged back to the current one). INFEASIBLE: no
    # candidate placement satisfies every constraint -- see
    # utils/csp_solver.py:solve_placement / decision_engine_cp_sat.py.
    outcome: Literal["FEASIBLE", "INFEASIBLE"] = "FEASIBLE"
    decision: dict[str, str]  # service_id -> new node_id
    eligible_nodes_considered: list[str]
    requirements_satisfied: list[str]
    new_configuration: dict[str, str]  # service_id -> node_id (full state)
    # Human-readable (ok/reason) trace of every check performed against the
    # chosen placement -- see utils/csp_checks.py.
    resolution_trace: list[str] = Field(default_factory=list)
    search_trace: list[str] = Field(default_factory=list)
